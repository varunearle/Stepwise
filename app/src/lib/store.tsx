const qByTopic = (t: TopicId) => QUESTIONS.filter((q) => q.topic === t);

/**
 * Builds the demo cohort: learners whose answers are generated by the BKT model
 * itself, each with their own starting knowledge and learning rate, spread over
 * the last nine days. They are clearly marked as simulated in the Class view.
 */
export function simulateCohort(seed: number, params: Record<TopicId, BktParams>, now = Date.now()): Attempt[] {
  const rand = seededRandom(seed);
  const out: Attempt[] = [];
  SIM_NAMES.forEach((_, si) => {
    const id = `s${String(si + 1).padStart(2, '0')}`;
    const ability = rand() * 2 - 1; // -1 weaker .. +1 stronger
    for (const t of TOPICS) {
      const p = params[t.id];
      const topicShift = (rand() - 0.5) * 0.4;
      let known = rand() < Math.min(0.85, Math.max(0.05, 0.2 + 0.3 * ability + topicShift));
      const learn = Math.min(0.6, Math.max(0.05, 0.12 + 0.08 * ability + (rand() - 0.5) * 0.1));
      const n = 4 + Math.floor(rand() * 8);
      const qs = qByTopic(t.id);
      const start = now - (9 - rand() * 3) * 86400000;
      for (let k = 0; k < n; k++) {
        const q = qs[k % qs.length];
        const correct = rand() < (known ? 1 - p.slip : p.guess);
        const wrong = [0, 1, 2, 3].filter((i) => i !== q.answer);
        const day = start + k * ((now - start - 3600000) / n);
        const at = Math.floor(day + rand() * 3600000);
        out.push({
          id: `${id}-${t.id}-${k}`, student: id, topic: t.id, question: q.id,
          chosen: correct ? q.answer : wrong[Math.floor(rand() * wrong.length)],
          correct, at,
        });
        if (!known && rand() < learn) known = true;
      }
    }
  });
  return out.sort((a, b) => a.at - b.at);
}

function fresh(): Persisted {
  const params = defaultParamsByTopic();
  const cohortSeed = 20261015;
  return {
    version: 1, attempts: simulateCohort(cohortSeed, params), params,
    studentName: 'Varun Sai', teacherName: 'Course instructor', cohortSeed,
  };
}

const TOPIC_IDS = new Set<string>(TOPICS.map((t) => t.id));
const QUESTION_IDS = new Set(QUESTIONS.map((q) => q.id));
const isProb = (x: unknown) => typeof x === 'number' && x > 0 && x < 1;
const cleanName = (x: unknown, fallback: string) =>
  typeof x === 'string' && x.trim() ? x.trim().slice(0, NAME_MAX) : fallback;

/** Keeps only well-formed attempts so edited or corrupted storage cannot break the app. */
function validAttempt(a: unknown): a is Attempt {
  const x = a as Attempt;
  return !!x && typeof x.id === 'string' && typeof x.student === 'string' && TOPIC_IDS.has(x.topic)
    && QUESTION_IDS.has(x.question) && Number.isInteger(x.chosen) && x.chosen >= 0 && x.chosen <= 3
    && typeof x.correct === 'boolean' && Number.isFinite(x.at)
    && x.correct === (x.chosen === QUESTIONS.find((q) => q.id === x.question)!.answer);
}

export function sanitize(d: unknown): Persisted | null {
  const x = d as Partial<Persisted> | null;
  if (!x || x.version !== 1 || !Array.isArray(x.attempts)) return null;
  const params = defaultParamsByTopic();
  for (const t of TOPICS) {
    const p = x.params?.[t.id];
    if (p && isProb(p.prior) && isProb(p.learn) && isProb(p.guess) && isProb(p.slip) && p.guess + p.slip < 1) params[t.id] = p;
  }
  return {
    version: 1,
    attempts: x.attempts.filter(validAttempt),
    params,
    studentName: cleanName(x.studentName, 'Varun Sai'),
    teacherName: cleanName(x.teacherName, 'Course instructor'),
    cohortSeed: Number.isInteger(x.cohortSeed) ? x.cohortSeed! : 20261015,
  };
}

function load(): Persisted {
  try {
    const raw = localStorage.getItem(KEY);
    const d = raw ? sanitize(JSON.parse(raw)) : null;
    if (d) return d;
  } catch { /* storage unavailable or unreadable: start fresh */ }
  return fresh();
}

function loadSession(): Session | null {
  try {
    const s = JSON.parse(sessionStorage.getItem(SESSION_KEY) ?? 'null');
    return s && (s.role === 'student' || s.role === 'teacher') ? { role: s.role } : null;
  } catch {
    return null;
  }
}

// ---------------------------------------------------------------- derived views

export interface TopicState {
  topic: TopicId;
  attempts: Attempt[];
  trace: number[]; // P(L) before first attempt, then after each attempt
  mastery: number;
  status: Status;
  correct: number;
}

export function topicState(all: Attempt[], student: string, topic: TopicId, p: BktParams): TopicState {
  const attempts = all.filter((a) => a.student === student && a.topic === topic).sort((a, b) => a.at - b.at);
  const tr = trace(attempts.map((a) => a.correct), p);
  const mastery = tr[tr.length - 1];
  return {
    topic, attempts, trace: tr, mastery, status: status(mastery, attempts.length),
    correct: attempts.filter((a) => a.correct).length,
  };
}

export interface Recommendation {
  topic: TopicId;
  reason: string;
}

/** Lowest estimated mastery among topics not yet mastered; course order breaks ties. */
export function recommend(states: TopicState[]): Recommendation | null {
  const open = states.filter((s) => s.mastery < MASTERY_THRESHOLD);
  if (open.length === 0) return null;
  const min = Math.min(...open.map((s) => s.mastery));
  const pick = open.find((s) => Math.abs(s.mastery - min) < 1e-9)!;
  const tied = open.filter((s) => Math.abs(s.mastery - min) < 1e-9).length;
  const reason = states.every((s) => s.attempts.length === 0)
    ? 'No attempts yet, so every topic starts at the same estimate. Starting with the first topic in course order.'
    : tied > 1
      ? 'Lowest estimated mastery among topics not yet mastered (tied; course order decides).'
      : 'Lowest estimated mastery among topics not yet mastered.';
  return { topic: pick.topic, reason };
}

/**
 * Next question in a topic: one not yet attempted, else the one answered wrongly most recently,
 * else the one practised least recently. `exclude` avoids repeating the question just answered.
 */
export function nextQuestion(all: Attempt[], student: string, topic: TopicId, exclude?: string): { q: Question; why: string } {
  const qs = qByTopic(topic);
  const mine = all.filter((a) => a.student === student && a.topic === topic);
  const last = new Map<string, Attempt>();
  for (const a of [...mine].sort((x, y) => x.at - y.at)) last.set(a.question, a);
  const pool = qs.length > 1 && exclude ? qs.filter((q) => q.id !== exclude) : qs;
  const unseen = pool.filter((q) => !last.has(q.id));
  if (unseen.length) return { q: unseen[0], why: 'You have not attempted this question yet.' };
  const wrong = pool.filter((q) => !last.get(q.id)!.correct).sort((a, b) => last.get(b.id)!.at - last.get(a.id)!.at);
  if (wrong.length) return { q: wrong[0], why: 'You answered this one incorrectly last time.' };
  const q = [...pool].sort((a, b) => last.get(a.id)!.at - last.get(b.id)!.at)[0];
  return { q, why: 'All questions in this topic have been attempted; this is the one practised longest ago.' };
}

// ---------------------------------------------------------------- context

interface Store {
  data: Persisted;
  session: Session | null;
  students: Student[];
  signIn: (s: Session) => void;
  signOut: () => void;
  answer: (q: Question, chosen: number) => { attempt: Attempt; detail: ReturnType<typeof update> };
  setNames: (studentName: string, teacherName: string) => void;
  resetMine: () => void;
  regenerateCohort: () => void;
  resetAll: () => void;
}

const Ctx = createContext<Store | null>(null);

export function StoreProvider({ children }: { children: ReactNode }) {
  const [data, setData] = useState<Persisted>(load);
  const [session, setSession] = useState<Session | null>(loadSession);

  useEffect(() => {
    try { localStorage.setItem(KEY, JSON.stringify(data)); } catch { /* ignore */ }
  }, [data]);
  useEffect(() => {
    try {
      if (session) sessionStorage.setItem(SESSION_KEY, JSON.stringify(session));
      else sessionStorage.removeItem(SESSION_KEY);
    } catch { /* ignore */ }
  }, [session]);

  const students = useMemo<Student[]>(
    () => [
      { id: ME, name: data.studentName, simulated: false },
      ...SIM_NAMES.map((name, i) => ({ id: `s${String(i + 1).padStart(2, '0')}`, name, simulated: true })),
    ],
    [data.studentName],
  );

  const answer = useCallback((q: Question, chosen: number) => {
    const correct = chosen === q.answer;
    const p = data.params[q.topic];
    const before = topicState(data.attempts, ME, q.topic, p).mastery;
    const detail = update(before, correct, p);
    const attempt: Attempt = {
      id: `me-${Date.now()}-${Math.floor(Math.random() * 1e6)}`,
      student: ME, topic: q.topic, question: q.id, chosen, correct, at: Date.now(),
    };
    setData((d) => ({ ...d, attempts: [...d.attempts, attempt] }));
    return { attempt, detail };
  }, [data]);

  const store: Store = {
    data, session, students,
    signIn: setSession,
    signOut: () => setSession(null),
    answer,
    setNames: (studentName, teacherName) => setData((d) => ({
      ...d,
      studentName: cleanName(studentName, 'Student'),
      teacherName: cleanName(teacherName, 'Course instructor'),
    })),
    resetMine: () => setData((d) => ({ ...d, attempts: d.attempts.filter((a) => a.student !== ME) })),
    regenerateCohort: () => setData((d) => {
      const seed = d.cohortSeed + 1;
      const mine = d.attempts.filter((a) => a.student === ME);
      return { ...d, cohortSeed: seed, attempts: [...simulateCohort(seed, d.params), ...mine] };
    }),
    resetAll: () => setData(fresh()),
  };
  return <Ctx.Provider value={store}>{children}</Ctx.Provider>;
}

export function useStore() {
  const s = useContext(Ctx);
  if (!s) throw new Error('useStore outside provider');
  return s;
}

export function useTopicStates(student: string): TopicState[] {
  const { data } = useStore();
  return useMemo(
    () => TOPICS.map((t) => topicState(data.attempts, student, t.id, data.params[t.id])),
    [data.attempts, data.params, student],
  );
}
